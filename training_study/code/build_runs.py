"""Rebuild RUNS.md: every training run, the exact command that produced it, and its last logged evaluation."""
import json, glob, os
here = os.path.dirname(os.path.abspath(__file__))
rows = []
for f in sorted(glob.glob(os.path.join(here, "results", "*.json"))):
    try: d = json.load(open(f))
    except Exception: continue
    if not isinstance(d, dict) or "args" not in d: continue
    a = d["args"]; script = "train_disc.py" if "k" in a else "train.py"
    flags = []
    for k, v in a.items():
        if v is False or v is None or v == "": continue
        flags.append(f"--{k}" if v is True else f"--{k} {v}")
    ev = d.get("evals", [])
    last = ev[-1] if ev else {}
    if script == "train_disc.py" and last:
        res = ", ".join(f"{k}: {v['solved_state']:.2f} state / {v['solved_readout']:.2f} readout" for k, v in last.items() if k.startswith("n"))
    elif last:
        t = last.get("test", {}); o = last.get("onestep", {})
        res = f"one-step cell acc {o.get('step_cell_acc', float('nan')):.4f}, changing cells {o.get('changed_cell_acc', float('nan')) if 'changed_cell_acc' in o else 'n/a'}, solved {t.get('solved_state', t.get('solved'))}"
    else:
        res = f"no evaluation logged{'; diverged at step ' + str(d['diverged_at']) if 'diverged_at' in d else ''}"
    rows.append((os.path.basename(f)[:-5], script, " ".join(flags), last.get("step", "-"), res))
out = ["# Every run", "",
       "Generated by `code/build_runs.py` from `code/results/*.json`. Run each command from `code/`.",
       "The scripts gained options over time; options added later default to off, so these commands reproduce each run's settings.",
       "Two things differ from the code at the time: D1-D4 ran before non-finite updates were skipped, and the R1-R7 `snap` numbers in the logs predate resetting the static numbers.",
       "D1 kept no settings file (its log says `diverged 175`).", "",
       "| Run | Script | Last eval step | Last evaluation |", "|---|---|---|---|"]
for name, script, flags, step, res in rows:
    out.append(f"| `{name}` | `{script}` | {step} | {res} |")
out += ["", "## Commands", ""]
for name, script, flags, step, res in rows:
    out.append(f"**{name}**\n```\npython {script} {flags}\n```")
open(os.path.join(here, "..", "RUNS.md"), "w").write("\n".join(out) + "\n")
print(len(rows), "runs")
